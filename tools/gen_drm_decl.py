"""Forward declarations for the Dreams port (docs/DREAMS_PLAN.md): a stub per non-static function of
ReflectionHLE's kdreams sources, as tools/gen_gal_decl.py does for the Galaxy port, but reading id's
style, where the return type stands on the line before the function's name.

    python tools/gen_drm_decl.py --list        # functions per file
    python tools/gen_drm_decl.py               # rewrite the GENERATED block of godot/games/dreams/drm_decl.gd
"""
import re
import sys
from pathlib import Path

import gen_gal_decl as gal

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "refkeen" / "src" / "kdreams"
OUT = ROOT / "godot" / "games" / "dreams" / "drm_decl.gd"
BEGIN = "# ---- GENERATED by tools/gen_drm_decl.py: forward declarations (do not edit) ----"
END = "# ---- END GENERATED ----"
# ReflectionHLE's own files and the releases the port does not support
SKIP = ("kl_", "altcontroller", "key_scancode", "statetype", "id_us_s_kdreams113", "id_us_s_kdreams120")
KEYWORDS = {"if", "while", "for", "switch", "return", "sizeof", "else", "do"}


def functions(path):
    """[(name, parameter count, static)] of the file's function definitions, in order."""
    text = gal.active_lines(gal.strip_comments(path.read_text(encoding="latin-1")))
    found = []
    for m in re.finditer(r"^((?:[A-Za-z_][\w \t\*]*?\b)?)([A-Za-z_]\w*)\s*\(", text, flags=re.M):
        ret, name = m.group(1).strip(), m.group(2)
        if name in KEYWORDS:
            continue
        i, depth = m.end(), 1
        while i < len(text) and depth:
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
        params = text[m.end():i - 1].strip()
        if not text[i:i + 200].lstrip().startswith("{"):
            continue
        if not ret:
            prev = text[:m.start()].rstrip().split("\n")[-1].strip()
            if not prev or prev.endswith((";", "}", "{", ")", ",")) or prev.startswith("#"):
                continue
            ret = prev
        static = ret.split()[0] == "static" if ret else False
        if params in ("", "void"):
            n = 0
        else:
            n, depth = 1, 0
            for c in params:
                depth += {"(": 1, ")": -1}.get(c, 0)
                if c == "," and depth == 0:
                    n += 1
        found.append((name, n, static))
    return found


def files():
    return [p for p in sorted(SRC.glob("*.c")) if not p.name.startswith(SKIP)]


def block():
    seen = {}
    lines = [BEGIN]
    for p in files():
        fresh = []
        for name, n, static in functions(p):
            if static or name in seen:
                continue
            seen[name] = n
            fresh.append((name, n))
        if fresh:
            lines += ["", f"# {p.name}"]
            for name, n in fresh:
                lines.append(f"func {name}({', '.join(f'_p{i}' for i in range(n))}):")
                lines.append(f"\treturn _undefined(&\"{name}\")")
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    if "--list" in sys.argv:
        total = 0
        for p in files():
            fns = functions(p)
            total += len(fns)
            print(f"{p.name:32s} {len(fns):3d} ({sum(1 for f in fns if f[2])} static)")
        print(total)
        return 0
    text = OUT.read_text(encoding="utf-8")
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1] if END in rest else ""
    OUT.write_bytes((head + block() + tail.lstrip("\n")).encode("utf-8"))
    print(f"{OUT.name} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
