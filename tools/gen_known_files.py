"""Write godot/shell/known_files.gd: the sizes and SHA-256 of every file of the
seven supported releases, read from the development copies in game_data/, plus
the hand-kept list of releases that are recognised but not supported (sizes and
CRC-32s from ReflectionHLE's be_gamedefs_kdreams.h).

A checksum is not the file; nothing of the games themselves is written.

Usage: python tools/gen_known_files.py
"""
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import common

SETS = [
    ("keen1", "Commander Keen 1: Marooned on Mars", "v1.31 EGA (Steam)", "vorticons", "KEEN1.EXE"),
    ("keen2", "Commander Keen 2: The Earth Explodes", "v1.31 EGA (Steam)", "vorticons", "KEEN2.EXE"),
    ("keen3", "Commander Keen 3: Keen Must Die!", "v1.31 EGA (Steam)", "vorticons", "KEEN3.EXE"),
    ("keen4", "Commander Keen 4: Secret of the Oracle", "v1.4 EGA (Steam)", "galaxy", "KEEN4E.EXE"),
    ("keen5", "Commander Keen 5: The Armageddon Machine", "v1.4 EGA (Steam)", "galaxy", "KEEN5E.EXE"),
    ("keen6", "Commander Keen 6: Aliens Ate My Babysitter!", "v1.0 EGA", "galaxy", "KEEN6C.EXE"),
    ("kdreams", "Keen Dreams", "v1.00 EGA (registered)", "dreams", "KDREAMS.EXE"),
]

# Files in game_data that are not part of the game (patchers, notes).
IGNORE = {"6KEEN14.EXE", "README.TXT", "CONFIG.CK4", "CONFIG.CK5", "CONFIG.CK6", "CONFIG.KDR"}

# Releases recognised by checksum and named as unsupported, with the remedy.
# From ReflectionHLE's table (CRC-32 of the whole file).
UNSUPPORTED = [
    ("kdreams", "Keen Dreams CGA v1.00", "KDREAMS.EXE", 75015, 0xB6FF595A),
    ("kdreams", "Keen Dreams CGA v1.05", "KDREAMS.EXE", 78253, 0x5AF7CE2B),
    ("kdreams", "Keen Dreams EGA v1.13 (shareware)", "KDREAMS.EXE", 81619, 0x9DCE0A39),
    ("kdreams", "Keen Dreams EGA v1.20", "KDREAMS.EXE", 81519, 0xF36F0EDF),
    ("kdreams", "Keen Dreams EGA v1.93", "KDREAMS.EXE", 80715, 0x3D0CD9ED),
    ("kdreams", "Keen Dreams 2015 (Steam)", "KDREAMS.EGA", 213221, 0xEE1024B9),
]
REMEDY = {
    "kdreams": "Megarocket reads the registered v1.00 EGA release: KDREAMS.EXE (77,694 bytes) with AUDIO, EGAGRAPH and GAMEMAPS .KDR beside it.",
}


def main():
    root = Path(common.config()["game_data"])
    out = []
    out.append("# Copyright (C) 2026 the Megarocket contributors. GPL v2 or later. See LICENSE.md.")
    out.append("#")
    out.append("# GENERATED by tools/gen_known_files.py from the development copies of the games;")
    out.append("# do not edit by hand. Checksums only: nothing of the games is in here.")
    out.append("class_name KnownFiles")
    out.append("extends RefCounted")
    out.append("## The seven supported releases, file by file (size and SHA-256), the")
    out.append("## releases recognised but not supported (ReflectionHLE's CRC-32s), and the")
    out.append("## remedy to name for each game.")
    out.append("")
    out.append("const SETS: Array = [")
    for gid, title, version, engine, exe in SETS:
        folder = root / gid
        files = sorted(p for p in folder.iterdir() if p.is_file() and p.name.upper() not in IGNORE)
        if not files:
            raise SystemExit(f"no files in {folder}")
        out.append("\t{")
        out.append(f'\t\t"id": "{gid}", "title": "{title}", "version": "{version}", "engine": "{engine}", "exe": "{exe}",')
        out.append('\t\t"files": {')
        for p in files:
            digest = hashlib.sha256(p.read_bytes()).hexdigest()
            out.append(f'\t\t\t"{p.name.upper()}": [{p.stat().st_size}, "{digest}"],')
        out.append("\t\t},")
        out.append("\t},")
    out.append("]")
    out.append("")
    out.append("## Releases this program recognises and does not read: [game id, name, file, size, CRC-32].")
    out.append("const UNSUPPORTED: Array = [")
    for gid, name, fname, size, crc in UNSUPPORTED:
        out.append(f'\t["{gid}", "{name}", "{fname}", {size}, 0x{crc:08X}],')
    out.append("]")
    out.append("")
    out.append("const REMEDY: Dictionary = {")
    for gid, title, version, engine, exe in SETS:
        if gid in REMEDY:
            text = REMEDY[gid]
        else:
            text = f"Megarocket reads {title.split(':')[0]} {version}: {exe} with its data files beside it, as sold on Steam."
        out.append(f'\t"{gid}": "{text}",')
    out.append("}")
    out.append("")
    target = Path(__file__).parent.parent / "godot" / "shell" / "known_files.gd"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
