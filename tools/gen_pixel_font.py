def write_gd():
    lines = [
        "# Copyright (C) 2026 the Megarocket contributors. GPL v2 or later. See LICENSE.md.",
        "# ---- GENERATED by tools/gen_pixel_font.py (do not edit) ----",
        "class_name PixelFontData",
        "extends RefCounted",
        "## Megarocket's own pixel font: each glyph %dx%d (%d rows above the baseline), rows top first," % (W, H, BASE),
        "## '#' a lit pixel. Drawn for the shell; no game's font, no system font.",
        "",
        "const W: int = %d" % W,
        "const H: int = %d" % H,
        "const BASE: int = %d" % BASE,
        "const GLYPHS: Dictionary = {",
    ]
    for ch, rows in G.items():
        key = ch.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('\t"%s": [%s],' % (key, ", ".join('"%s"' % r for r in rows)))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def sample(path):
    from PIL import Image
    text = ["Megarocket  MEGAROCKET  0123456789",
            "The quick brown fox jumps over the lazy dog.",
            "THE QUICK BROWN FOX JUMPS OVER THE LAZY DOG!",
            "Ready · v1.31 EGA (Steam)  Not found? Add a folder…",
            "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~ ▶ ◀ — –",
            "Commander Keen 4: Secret of the Oracle"]
    scale = 3
    adv, lh = W + 1, H + 3
    width = max(len(t) for t in text) * adv + 4
    img = Image.new("RGB", (width * scale, (len(text) * lh + 4) * scale), (0, 0, 40))
    px = img.load()
    for li, t in enumerate(text):
        for ci, ch in enumerate(t):
            rows = G.get(ch, G["?"])
            for y, r in enumerate(rows):
                for x, c in enumerate(r):
                    if c == "#":
                        X, Y = 2 + ci * adv + x, 2 + li * lh + y
                        for dx in range(scale):
                            for dy in range(scale):
                                px[X * scale + dx, Y * scale + dy] = (255, 255, 85)
    img.save(path)


if __name__ == "__main__":
    write_gd()
    print(f"{OUT.name}: {len(G)} glyphs")
    if len(sys.argv) > 1:
        sample(sys.argv[1])
