"""The constants of the Dreams port (docs/DREAMS_PLAN.md): every numeric `#define` and every enum member
of ReflectionHLE's kdreams headers, as GDScript constants, into the CONSTANTS block of
godot/games/dreams/drm_decl.gd. Only definitions whose value is an integer expression over earlier
constants are taken (macros with parameters, strings and types are written by hand); `#if 0` blocks
are skipped; the first definition of a name wins (G_P_SHIFT is defined twice, the same).

    python tools/gen_drm_consts.py          # rewrite the block
    python tools/gen_drm_consts.py --list   # print what would be written
"""
import re
import sys
from pathlib import Path

import gen_gal_decl as gal
from c_lex import strip_comments

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "refkeen" / "src" / "kdreams"
OUT = ROOT / "godot" / "games" / "dreams" / "drm_decl.gd"
BEGIN = "# ---- GENERATED by tools/gen_drm_consts.py: constants (do not edit) ----"
END = "# ---- END GENERATED CONSTANTS ----"
HEADERS = ["graphkdr.h", "audiokdr.h", "id_mm.h", "id_ca.h", "id_vw.h", "id_rf.h", "id_in.h", "id_sd.h",
           "id_us.h", "soft.h", "sl_file.h", "jam_io.h", "lzhuff.h", "lzw.h", "gelib.h", "kd_def.h"]
TOKEN = re.compile(r"\s*(0[xX][0-9a-fA-F]+[uUlL]*|\d+[uUlL]*|[A-Za-z_]\w*|\|\||&&|<<|>>|[-+*/()|&~^%])")
# Names the port declares by hand (they are variables or depend on the version at run time)
SKIP = {"__ID_GLOB__", "EXTENSION", "GREXT", "TEXTGR", "CGAGR", "EGAGR", "VGAGR", "id0_nil_t", "id0_far",
        "id0_huge", "id0_seg", "id0_argc", "id0_argv"}


def expression(value, known):
    """The GDScript form of an integer C expression over `known` names, else None."""
    out, pos = [], 0
    value = value.strip()
    if not value:
        return None
    while pos < len(value):
        m = TOKEN.match(value, pos)
        if not m:
            return None
        tok = m.group(1)
        pos = m.end()
        if tok in ("||", "&&"):
            return None    # a truth value, not an integer
        if tok[0].isdigit():
            tok = tok.rstrip("uUlL")
            if len(tok) > 1 and tok[0] == "0" and tok[1] not in "xX":
                tok = str(int(tok, 8))
        elif tok[0].isalpha() or tok[0] == "_":
            if tok not in known:
                return None
        out.append(tok)
    return " ".join(out).replace("( ", "(").replace(" )", ")")


def constants():
    known, out = set(), []
    for name in HEADERS:
        text = gal.active_lines(strip_comments((SRC / name).read_text(encoding="latin-1")))
        section = []
        for m in re.finditer(r"^[ \t]*#define[ \t]+([A-Za-z_]\w*)(\(?)([^\n]*)$", text, flags=re.M):
            ident, paren, value = m.group(1), m.group(2), m.group(3)
            if paren or ident in known or ident in SKIP:
                continue
            expr = expression(value, known)
            if expr is None:
                continue
            known.add(ident)
            section.append(f"const {ident}: int = {expr}")
        for m in re.finditer(r"typedef\s+enum\s*\{([^}]*)\}\s*(\w+)\s*;", text):
            nxt = 0
            prev = None
            members = []
            for part in m.group(1).split(","):
                part = part.strip()
                if not part:
                    continue
                ident, _, value = part.partition("=")
                ident = ident.strip()
                if value.strip():
                    expr = expression(value, known | {x for x, _ in members})
                    if expr is None:
                        break
                    val = expr
                else:
                    val = str(nxt) if prev is None else f"{prev} + 1"
                members.append((ident, val))
                prev = ident
                nxt += 1
            else:
                section.append(f"# {m.group(2)}")
                for ident, val in members:
                    if ident in known:
                        continue
                    known.add(ident)
                    section.append(f"const {ident}: int = {val}")
        if section:
            out += ["", f"# {name}"] + section
    return out


def block():
    return "\n".join([BEGIN] + constants() + [END]) + "\n"


def main():
    if "--list" in sys.argv:
        lines = constants()
        print("\n".join(lines))
        print(sum(1 for line in lines if line.startswith("const")), "constants")
        return 0
    text = OUT.read_text(encoding="utf-8")
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1] if END in rest else ""
    OUT.write_bytes((head + block() + tail.lstrip("\n")).encode("utf-8"))
    print(f"{OUT.name}: constants written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
