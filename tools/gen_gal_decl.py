"""Generate the forward declarations of the Galaxy port (docs/GALAXY_PLAN.md, convention 3).

Every non-static function defined in omnispeak's ck_*.c and ck4/5/6_*.c files gets an untyped stub in
godot/games/galaxy/gal_ck.gd, between the GENERATED markers, so a script early in the chain can call a
function a later script defines (the later script overrides it with a typed signature of the same arity).
Functions the id_* layers already define (GalLib..GalUS) are skipped.

    python tools/gen_gal_decl.py          # rewrite the generated block
    python tools/gen_gal_decl.py --check  # exit 1 if the block is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "omnispeak-ref" / "src"
OUT = ROOT / "godot" / "games" / "galaxy" / "gal_ck.gd"
EARLIER = ["gal_lib.gd", "gal_rf.gd", "gal_io.gd", "gal_us.gd"]
BEGIN = "# ---- GENERATED by tools/gen_gal_decl.py: forward declarations (do not edit) ----"
END = "# ---- END GENERATED ----"

FILES = ["ck_phys.c", "ck_obj.c", "ck_misc.c", "ck_map.c", "ck_play.c", "ck_keen.c",
         "ck_main.c", "ck_game.c", "ck_text.c", "ck_inter.c", "ck_quit.c", "ck_us_2.c"]
FILES += sorted(p.name for p in SRC.glob("ck[456]_*.c"))

KEYWORDS = {"if", "while", "for", "switch", "return", "sizeof", "else", "do"}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def active_lines(text):
    """Drop `#if 0` blocks (not other conditionals: both sides of those are real code)."""
    out, depth = [], 0
    for line in text.split("\n"):
        s = line.strip()
        if depth:
            if s.startswith("#if"):
                depth += 1
            elif s.startswith("#endif"):
                depth -= 1
            elif s.startswith("#else") and depth == 1:
                depth = 0
            out.append("")
            continue
        if re.match(r"#\s*if\s+0\b", s):
            depth = 1
            out.append("")
            continue
        out.append(line)
    return "\n".join(out)


def functions(path):
    text = active_lines(strip_comments(path.read_text(encoding="latin-1")))
    found = []
    for m in re.finditer(r"^([A-Za-z_][\w \t\*]*?)\b([A-Za-z_]\w*)\s*\(", text, flags=re.M):
        ret, name = m.group(1).strip(), m.group(2)
        if name in KEYWORDS or ret.startswith(("static", "return", "else", "typedef", "extern")) or ret == "":
            continue
        # balanced parameter list
        i, depth = m.end(), 1
        while i < len(text) and depth:
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
        params = text[m.end():i - 1]
        rest = text[i:i + 200].lstrip()
        if not rest.startswith("{"):
            continue          # a prototype or a call
        params = params.strip()
        if params in ("", "void"):
            n = 0
        else:
            depth, n = 0, 1
            for c in params:
                depth += {"(": 1, ")": -1}.get(c, 0)
                if c == "," and depth == 0:
                    n += 1
        found.append((name, n))
    return found


def earlier_defined():
    """Functions the id_* scripts and gal_ck.gd's own hand-written part define, and C's main."""
    names = {"main"}
    texts = [(ROOT / "godot/games/galaxy" / f).read_text(encoding="utf-8") for f in EARLIER]
    texts.append(OUT.read_text(encoding="utf-8").split(BEGIN, 1)[0])
    for t in texts:
        for m in re.finditer(r"^(?:static )?func (\w+)", t, flags=re.M):
            names.add(m.group(1))
    return names


def block():
    skip = earlier_defined()
    seen = {}
    lines = [BEGIN]
    for f in FILES:
        p = SRC / f
        if not p.exists():
            continue
        fns = [(n, k) for n, k in functions(p) if n not in skip]
        fresh = []
        for n, k in fns:
            if n in seen:
                if seen[n] != k:
                    sys.exit(f"{n}: defined with {seen[n]} and {k} parameters")
                continue
            seen[n] = k
            fresh.append((n, k))
        if not fresh:
            continue
        lines.append("")
        lines.append(f"# {f}")
        for n, k in fresh:
            args = ", ".join(f"_p{i}" for i in range(k))
            lines.append(f"func {n}({args}):")
            lines.append(f"\treturn _undefined(&\"{n}\")")
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    text = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if BEGIN not in text:
        sys.exit(f"{OUT}: no generated block markers")
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1] if END in rest else ""
    new = head + block() + tail.lstrip("\n")
    if "--check" in sys.argv:
        sys.exit(0 if new == text else 1)
    OUT.write_bytes(new.encode("utf-8"))
    print(f"{OUT.name}: {new.count(chr(10) + 'func ')} declarations")


if __name__ == "__main__":
    main()
